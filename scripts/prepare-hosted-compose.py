#!/usr/bin/env python3
"""Verify the hosted release and generate its immutable Compose image input."""

from __future__ import annotations

import argparse
import importlib.util
import os
from pathlib import Path
from typing import Any


_VERIFIER_PATH = Path(__file__).with_name("verify-hosted-release.py")
_SPEC = importlib.util.spec_from_file_location("verify_hosted_release", _VERIFIER_PATH)
if _SPEC is None or _SPEC.loader is None:  # pragma: no cover - installation failure
    raise RuntimeError(f"cannot load hosted release verifier from {_VERIFIER_PATH}")
_VERIFIER = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_VERIFIER)


class ComposePreparationError(RuntimeError):
    """Raised before Compose can consume an untrusted hosted image."""


def _reject_mismatched_override(name: str, expected: str) -> None:
    supplied = os.environ.get(name)
    if supplied is not None and supplied != expected:
        raise ComposePreparationError(
            f"{name} does not match the verified hosted release"
        )


def prepare_compose_env(
    *, trust_path: Path, manifest_path: Path, wheel_path: Path, output_path: Path
) -> str:
    result: dict[str, Any] = _VERIFIER.verify_release(
        trust_path=trust_path,
        manifest_path=manifest_path,
        wheel_path=wheel_path,
    )
    reference = str(result["service_image_reference"])
    digest = str(result["service_image_digest"])
    verified_image = f"{reference}@{digest}"

    # Legacy split inputs and the generated input itself are never operator
    # selectors. If present, they must already equal the signed release.
    _reject_mismatched_override("HOSTED_SETTLEMENT_IMAGE_REFERENCE", reference)
    _reject_mismatched_override("HOSTED_SETTLEMENT_IMAGE_DIGEST", digest)
    _reject_mismatched_override("HOSTED_SETTLEMENT_VERIFIED_IMAGE", verified_image)

    content = (
        "# Generated by scripts/prepare-hosted-compose.py; do not edit.\n"
        f"HOSTED_SETTLEMENT_VERIFIED_IMAGE={verified_image}\n"
        f"HOSTED_SETTLEMENT_VERIFIED_MANIFEST_SHA256=sha256:{result['manifest_sha256']}\n"
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = output_path.with_name(f".{output_path.name}.tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(output_path)
    return verified_image


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--trust", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--wheel", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        image = prepare_compose_env(
            trust_path=args.trust,
            manifest_path=args.manifest,
            wheel_path=args.wheel,
            output_path=args.output,
        )
    except (_VERIFIER.ReleaseVerificationError, ComposePreparationError) as exc:
        parser.error(str(exc))
    print(image)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
